-- =====================================================================
-- PTrinity - DDL
-- Estructuras de persistencia para clientes, cuentas y movimientos.
-- Compatible con PostgreSQL (producción) y H2 en modo PostgreSQL (pruebas).
-- Las reglas críticas se refuerzan también a nivel de base de datos (CHECK,
-- UNIQUE y FOREIGN KEY) para garantizar la consistencia (la "C" de ACID).
-- =====================================================================

CREATE TABLE customers (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identification_type   VARCHAR(5)   NOT NULL,
    identification_number VARCHAR(20)  NOT NULL,
    first_name            VARCHAR(100) NOT NULL,
    last_name             VARCHAR(100) NOT NULL,
    email                 VARCHAR(150) NOT NULL,
    birth_date            DATE         NOT NULL,
    created_at            TIMESTAMP    NOT NULL,
    updated_at            TIMESTAMP,
    CONSTRAINT uk_customers_identification UNIQUE (identification_type, identification_number),
    CONSTRAINT uk_customers_email UNIQUE (email),
    CONSTRAINT ck_customers_identification_type CHECK (identification_type IN ('CC', 'CE', 'PA', 'PPT')),
    CONSTRAINT ck_customers_first_name_length CHECK (CHAR_LENGTH(first_name) >= 2),
    CONSTRAINT ck_customers_last_name_length CHECK (CHAR_LENGTH(last_name) >= 2),
    -- Un cliente no puede existir en base de datos si es menor de edad
    CONSTRAINT ck_customers_adult CHECK (birth_date <= CAST(created_at - INTERVAL '18' YEAR AS DATE))
);

CREATE TABLE accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_type    VARCHAR(10)    NOT NULL,
    account_number  VARCHAR(10)    NOT NULL,
    status          VARCHAR(10)    NOT NULL,
    balance         NUMERIC(19, 2) NOT NULL DEFAULT 0,
    overdraft_limit NUMERIC(19, 2) NOT NULL DEFAULT 0,
    gmf_exempt      BOOLEAN        NOT NULL DEFAULT FALSE,
    customer_id     BIGINT         NOT NULL,
    created_at      TIMESTAMP      NOT NULL,
    updated_at      TIMESTAMP,
    version         BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_accounts_number UNIQUE (account_number),
    -- Un producto solo puede existir vinculado a un cliente; un cliente con productos no se puede eliminar
    CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,
    CONSTRAINT ck_accounts_type CHECK (account_type IN ('SAVINGS', 'CHECKING')),
    CONSTRAINT ck_accounts_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'CANCELLED')),
    CONSTRAINT ck_accounts_number_format CHECK (
        CHAR_LENGTH(account_number) = 10
        AND ((account_type = 'SAVINGS' AND account_number LIKE '53%')
          OR (account_type = 'CHECKING' AND account_number LIKE '33%'))),
    CONSTRAINT ck_accounts_savings_non_negative CHECK (account_type <> 'SAVINGS' OR balance >= 0),
    CONSTRAINT ck_accounts_overdraft CHECK (balance >= -overdraft_limit),
    CONSTRAINT ck_accounts_cancelled_zero_balance CHECK (status <> 'CANCELLED' OR balance = 0)
);

CREATE INDEX ix_accounts_customer ON accounts (customer_id);

CREATE TABLE transactions (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference                  VARCHAR(36)    NOT NULL,
    transaction_type           VARCHAR(10)    NOT NULL,
    movement_type              VARCHAR(6)     NOT NULL,
    account_id                 BIGINT         NOT NULL,
    amount                     NUMERIC(19, 2) NOT NULL,
    gmf_amount                 NUMERIC(19, 2) NOT NULL DEFAULT 0,
    balance_after              NUMERIC(19, 2) NOT NULL,
    counterpart_account_number VARCHAR(10),
    description                VARCHAR(255),
    created_at                 TIMESTAMP      NOT NULL,
    CONSTRAINT fk_transactions_account FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE RESTRICT,
    CONSTRAINT ck_transactions_type CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    CONSTRAINT ck_transactions_movement CHECK (movement_type IN ('CREDIT', 'DEBIT')),
    CONSTRAINT ck_transactions_amount CHECK (amount > 0),
    CONSTRAINT ck_transactions_gmf CHECK (gmf_amount >= 0)
);

CREATE INDEX ix_transactions_account ON transactions (account_id);
CREATE INDEX ix_transactions_reference ON transactions (reference);

-- Consecutivos para generar números de cuenta únicos (53XXXXXXXX y 33XXXXXXXX)
CREATE SEQUENCE savings_account_number_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE checking_account_number_seq START WITH 1 INCREMENT BY 1;
