-- =====================================================================
-- PTrinity - DDL
-- Las restricciones replican en la base de datos las reglas del dominio,
-- para que ningun dato invalido pueda existir aunque se escriba por fuera de la API.
-- =====================================================================

CREATE TABLE clientes (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_identificacion   VARCHAR(20)  NOT NULL,
    numero_identificacion VARCHAR(20)  NOT NULL,
    nombres               VARCHAR(100) NOT NULL,
    apellido              VARCHAR(100) NOT NULL,
    correo                VARCHAR(150) NOT NULL,
    fecha_nacimiento      DATE         NOT NULL,
    fecha_creacion        TIMESTAMP    NOT NULL,
    fecha_modificacion    TIMESTAMP    NOT NULL,
    CONSTRAINT uk_clientes_identificacion UNIQUE (tipo_identificacion, numero_identificacion),
    CONSTRAINT ck_clientes_tipo_identificacion CHECK (tipo_identificacion IN ('CC', 'CE', 'PASAPORTE')),
    CONSTRAINT ck_clientes_nombres CHECK (CHAR_LENGTH(nombres) >= 2),
    CONSTRAINT ck_clientes_apellido CHECK (CHAR_LENGTH(apellido) >= 2),
    CONSTRAINT ck_clientes_correo CHECK (correo LIKE '_%@_%._%'),
    -- Un cliente menor de edad no puede existir en la base de datos
    CONSTRAINT ck_clientes_mayor_edad CHECK (fecha_nacimiento <= CURRENT_DATE - INTERVAL '18' YEAR)
);

CREATE TABLE cuentas (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_cuenta        VARCHAR(20)    NOT NULL,
    numero_cuenta      VARCHAR(10)    NOT NULL,
    estado             VARCHAR(20)    NOT NULL,
    saldo              NUMERIC(18, 2) NOT NULL DEFAULT 0,
    exenta_gmf         BOOLEAN        NOT NULL DEFAULT FALSE,
    fecha_creacion     TIMESTAMP      NOT NULL,
    fecha_modificacion TIMESTAMP      NOT NULL,
    -- Un producto solo existe vinculado a un cliente; el cliente no se borra si tiene productos
    cliente_id         BIGINT         NOT NULL,
    CONSTRAINT fk_cuentas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id) ON DELETE RESTRICT,
    CONSTRAINT uk_cuentas_numero UNIQUE (numero_cuenta),
    CONSTRAINT ck_cuentas_tipo CHECK (tipo_cuenta IN ('AHORROS', 'CORRIENTE')),
    CONSTRAINT ck_cuentas_estado CHECK (estado IN ('ACTIVA', 'INACTIVA', 'CANCELADA')),
    CONSTRAINT ck_cuentas_numero CHECK (
        CHAR_LENGTH(numero_cuenta) = 10
        AND ((tipo_cuenta = 'AHORROS' AND numero_cuenta LIKE '53%')
          OR (tipo_cuenta = 'CORRIENTE' AND numero_cuenta LIKE '33%'))),
    CONSTRAINT ck_cuentas_saldo_ahorros CHECK (tipo_cuenta <> 'AHORROS' OR saldo >= 0),
    CONSTRAINT ck_cuentas_cancelada_sin_saldo CHECK (estado <> 'CANCELADA' OR saldo = 0)
);

CREATE INDEX idx_cuentas_cliente ON cuentas (cliente_id);

CREATE TABLE movimientos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id          BIGINT         NOT NULL,
    tipo               VARCHAR(20)    NOT NULL,
    naturaleza         VARCHAR(10)    NOT NULL,
    monto              NUMERIC(18, 2) NOT NULL,
    gmf                NUMERIC(18, 2) NOT NULL DEFAULT 0,
    saldo_resultante   NUMERIC(18, 2) NOT NULL,
    -- Agrupa el debito y el credito de una misma transferencia
    referencia         VARCHAR(36)    NOT NULL,
    cuenta_contraparte VARCHAR(10),
    descripcion        VARCHAR(255),
    fecha              TIMESTAMP      NOT NULL,
    CONSTRAINT fk_movimientos_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuentas (id) ON DELETE RESTRICT,
    CONSTRAINT ck_movimientos_tipo CHECK (tipo IN ('CONSIGNACION', 'RETIRO', 'TRANSFERENCIA')),
    CONSTRAINT ck_movimientos_naturaleza CHECK (naturaleza IN ('CREDITO', 'DEBITO')),
    CONSTRAINT ck_movimientos_coherencia CHECK (
        (tipo = 'CONSIGNACION' AND naturaleza = 'CREDITO')
        OR (tipo = 'RETIRO' AND naturaleza = 'DEBITO')
        OR (tipo = 'TRANSFERENCIA' AND cuenta_contraparte IS NOT NULL)),
    CONSTRAINT ck_movimientos_monto CHECK (monto > 0),
    CONSTRAINT ck_movimientos_gmf CHECK (gmf >= 0)
);

CREATE INDEX idx_movimientos_cuenta_fecha ON movimientos (cuenta_id, fecha);
CREATE INDEX idx_movimientos_referencia ON movimientos (referencia);
